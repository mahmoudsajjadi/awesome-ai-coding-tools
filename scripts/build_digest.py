import os
import json
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DISCOVERIES_JSON = REPO_ROOT / 'docs' / 'discovered_candidates.json'
METADATA_JSON = REPO_ROOT / 'docs' / 'catalog_metadata.json'
DIGESTS_DIR = REPO_ROOT / 'docs' / 'digests'
LATEST_DIGEST_MD = REPO_ROOT / 'docs' / 'LATEST_DIGEST.md'

def format_number(num):
    if num is None:
        return 'N/A'
    if num >= 1000:
        return f"{num / 1000:.1f}k"
    return str(num)

def generate_digest():
    now = datetime.now(timezone.utc)
    week_str = now.strftime('%Y-W%U')
    date_str = now.strftime('%Y-%m-%d')
    
    DIGESTS_DIR.mkdir(parents=True, exist_ok=True)
    digest_path = DIGESTS_DIR / f"{date_str}-digest.md"

    candidates = []
    if DISCOVERIES_JSON.exists():
        with open(DISCOVERIES_JSON, 'r', encoding='utf-8') as f:
            candidates_data = json.load(f)
            candidates = candidates_data.get('candidates', [])

    top_catalog = []
    if METADATA_JSON.exists():
        with open(METADATA_JSON, 'r', encoding='utf-8') as f:
            meta_data = json.load(f)
            tools = meta_data.get('tools', [])
            # filter for github tools with stars
            gh_tools = [t for t in tools if t.get('is_github') and t.get('stars') is not None]
            gh_tools.sort(key=lambda x: x.get('stars', 0), reverse=True)
            top_catalog = gh_tools[:10]

    md_lines = [
        f"# AI Coding & MCP Ecosystem Digest ({date_str})",
        "",
        f"> Automatically generated by [awesome-ai-coding-tools](https://github.com/mahmoudsajjadi/awesome-ai-coding-tools) on {now.strftime('%B %d, %Y')}.",
        "",
        "## 🔥 Trending Newly Discovered Repositories & MCP Servers",
        "",
        "Recently active open-source AI coding assistants, MCP servers, and LLM devtools surfaced across the GitHub ecosystem this week:",
        "",
        "| Project | Stars | License | Description |",
        "| :--- | :---: | :---: | :--- |"
    ]

    if candidates:
        for c in candidates[:15]:
            name = c.get('name', 'Unknown')
            url = c.get('url', '#')
            stars = format_number(c.get('stars'))
            license_spdx = c.get('license') or 'N/A'
            desc = (c.get('description') or 'No description provided.').replace('|', '\\|').replace('\n', ' ')
            if len(desc) > 120:
                desc = desc[:117] + '...'
            md_lines.append(f"| [{name}]({url}) | ⭐ {stars} | `{license_spdx}` | {desc} |")
    else:
        md_lines.append("| *No new discoveries this cycle* | - | - | - |")

    md_lines.extend([
        "",
        "## 🏆 Top Catalog Projects by Community Traction",
        "",
        "The highest-starred verified projects tracked in our core catalog:",
        "",
        "| Project | Stars | Status | Category |",
        "| :--- | :---: | :---: | :--- |"
    ])

    if top_catalog:
        for t in top_catalog:
            name = t.get('name')
            url = t.get('url')
            stars = format_number(t.get('stars'))
            status = t.get('status', 'active').capitalize()
            cat = t.get('category', 'DevTool')
            md_lines.append(f"| [{name}]({url}) | ⭐ {stars} | {status} | {cat} |")

    md_lines.extend([
        "",
        "---",
        "",
        "### Want your tool or MCP server featured?",
        "- Submit a pull request or open an issue at [awesome-ai-coding-tools](https://github.com/mahmoudsajjadi/awesome-ai-coding-tools).",
        "- All entries are validated against open-source metadata standards and verified for active development."
    ])

    content = '\n'.join(md_lines) + '\n'

    with open(digest_path, 'w', encoding='utf-8') as f:
        f.write(content)

    with open(LATEST_DIGEST_MD, 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"Weekly digest successfully created at {digest_path} and {LATEST_DIGEST_MD}")

if __name__ == '__main__':
    generate_digest()
