import os
import json
import urllib.request
import urllib.parse
from datetime import datetime, timezone, timedelta
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DISCOVERIES_JSON = REPO_ROOT / 'docs' / 'discovered_candidates.json'
TOOLS_JSON = REPO_ROOT / 'docs' / 'tools.json'
GH_TOKEN = os.environ.get('GH_TOKEN') or os.environ.get('GITHUB_TOKEN')
ISSUE_BODY_MD = REPO_ROOT / 'docs' / 'DISCOVERY_ISSUE_BODY.md'

SEARCH_QUERIES = [
    'topic:mcp-server stars:>50',
    'topic:coding-agent stars:>30',
    'topic:ai-coding stars:>100'
]

def search_github(query):
    # Search for repositories pushed within the last 30 days
    since = (datetime.now(timezone.utc) - timedelta(days=30)).strftime('%Y-%m-%d')
    q = f"{query} pushed:>{since}"
    url = f"https://api.github.com/search/repositories?q={urllib.parse.quote(q)}&sort=stars&order=desc&per_page=10"
    
    req = urllib.request.Request(url)
    req.add_header('User-Agent', 'AwesomeAICodingTools-Discovery/1.0')
    req.add_header('Accept', 'application/vnd.github.v3+json')
    if GH_TOKEN:
        req.add_header('Authorization', f'Bearer {GH_TOKEN}')
    
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            if resp.status == 200:
                return json.loads(resp.read().decode('utf-8')).get('items', [])
    except Exception as e:
        print(f"Error querying GitHub search '{query}': {e}")
    return []

def format_number(num):
    if num is None:
        return 'N/A'
    if num >= 1000:
        return f"{num / 1000:.1f}k"
    return str(num)

def create_issue_body(candidates, date_str):
    lines = [
        f"## Ecosystem Discovery: Candidate Tools for Human Review ({date_str})",
        "",
        "The automated weekly discovery job scanned GitHub for trending repositories matching `coding-agent`, `mcp-server`, and `ai-coding`.",
        "",
        "Maintainers: review candidates below against catalog inclusion criteria (active maintenance, substantive functionality, non-promotional description, HTTPS repo). Check off items once reviewed or added to `README.md`.",
        "",
        "### Discovered Candidates Checklist",
        ""
    ]

    if not candidates:
        lines.append("- [ ] No new candidates met the inclusion threshold this week.")
    else:
        for c in candidates:
            name = c.get('name', 'Unknown')
            url = c.get('url', '#')
            full_name = c.get('full_name', name)
            stars = format_number(c.get('stars', 0))
            license_spdx = c.get('license') or 'Unspecified license'
            desc = (c.get('description') or 'No description provided.').replace('\n', ' ')
            topics = ", ".join(c.get('topics', [])[:5]) or "none"
            lines.append(f"- [ ] **[{full_name}]({url})** (⭐ {stars} | `{license_spdx}` | topics: {topics})")
            lines.append(f"  - *Description:* {desc}")
            lines.append(f"  - *Action:* [ ] Add to catalog / [ ] Reject / [ ] Needs more maturity")

    lines.extend([
        "",
        "---",
        "*Automated candidate review generated by `.github/workflows/weekly-discovery.yml`.*"
    ])

    return '\n'.join(lines) + '\n'

def main():
    print("Searching GitHub for trending AI coding tools & MCP servers...")

    # Load existing tools to avoid duplicates
    existing_urls = set()
    if TOOLS_JSON.exists():
        with open(TOOLS_JSON, 'r', encoding='utf-8') as f:
            tdata = json.load(f)
            for t in tdata.get('tools', []):
                existing_urls.add(t.get('url', '').strip().rstrip('/'))

    candidates = []
    seen_ids = set()

    for q in SEARCH_QUERIES:
        items = search_github(q)
        for it in items:
            repo_id = it.get('id')
            html_url = it.get('html_url', '').rstrip('/')
            
            if repo_id in seen_ids or html_url in existing_urls:
                continue
            
            seen_ids.add(repo_id)
            candidates.append({
                'name': it.get('name'),
                'full_name': it.get('full_name'),
                'url': html_url,
                'stars': it.get('stargazers_count', 0),
                'description': it.get('description') or 'No description provided.',
                'topics': it.get('topics', []),
                'license': it.get('license', {}).get('spdx_id') if it.get('license') else None,
                'pushed_at': it.get('pushed_at'),
                'discovered_at': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
            })

    # Sort by stars
    candidates.sort(key=lambda x: x['stars'], reverse=True)
    top_candidates = candidates[:25]

    output = {
        'generatedAt': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'candidateCount': len(candidates),
        'candidates': top_candidates
    }

    DISCOVERIES_JSON.parent.mkdir(parents=True, exist_ok=True)
    with open(DISCOVERIES_JSON, 'w', encoding='utf-8') as f:
        json.dump(output, f, indent=2)

    date_str = datetime.now(timezone.utc).strftime('%Y-%m-%d')
    issue_body = create_issue_body(top_candidates, date_str)
    with open(ISSUE_BODY_MD, 'w', encoding='utf-8') as f:
        f.write(issue_body)

    print(f"Discovery complete! Found {len(candidates)} new candidates. Saved top entries to {DISCOVERIES_JSON} and review body to {ISSUE_BODY_MD}")

if __name__ == '__main__':
    main()
